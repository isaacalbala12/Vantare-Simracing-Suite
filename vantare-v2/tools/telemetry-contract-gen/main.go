func (g *generator) writeTelemetryField(output *bytes.Buffer) error {
	fields, err := g.jsonFields(reflect.TypeFor[projection.Field[string]]())
	if err != nil {
		return fmt.Errorf("generate TelemetryField: %w", err)
	}
	output.WriteString("export interface TelemetryField<T> {\n")
	for _, field := range fields {
		typeName := "T"
		if field.name != "value" {
			typeName, err = g.typeScriptType(field.typeOf)
			if err != nil {
				return fmt.Errorf("generate TelemetryField.%s: %w", field.name, err)
			}
		}
		fmt.Fprintf(output, "  readonly %s: %s;\n", field.name, typeName)
	}
	output.WriteString("}\n")
	return nil
}

func (g *generator) writeOverlayQValue(output *bytes.Buffer) error {
	fields, err := g.jsonFields(reflect.TypeFor[overlayv2.QValue[string]]())
	if err != nil {
		return fmt.Errorf("generate OverlayQValue: %w", err)
	}
	output.WriteString("export interface OverlayQValue<T> {\n")
	for _, field := range fields {
		typeName := "T"
		if field.name != "v" {
			typeName, err = g.typeScriptType(field.typeOf)
			if err != nil {
				return fmt.Errorf("generate OverlayQValue.%s: %w", field.name, err)
			}
		}
		optional := ""
		if field.optional {
			optional = "?"
			typeName += " | undefined"
		}
		fmt.Fprintf(output, "  readonly %s%s: %s;\n", field.name, optional, typeName)
	}
	output.WriteString("}\n")
	return nil
}

func (g *generator) addEnum(typeOf reflect.Type, name string, values []string) {
	sort.Strings(values)
	g.claimName(typeOf, name)
	g.enums[typeOf] = enumRoot{typeOf: typeOf, name: name, values: values}
}

func (g *generator) addStruct(typeOf reflect.Type, name string) {
	g.claimName(typeOf, name)
	g.structs[typeOf] = structRoot{typeOf: typeOf, name: name}
}

func (g *generator) claimName(typeOf reflect.Type, name string) {
	if previous, exists := g.reserved[name]; exists && previous != typeOf {
		panic(fmt.Sprintf("generated TypeScript name %q is shared by %s and %s", name, previous, typeOf))
	}
	g.reserved[name] = typeOf
	g.names[typeOf] = name
}

func (g *generator) writeInterface(output *bytes.Buffer, root structRoot) error {
	fields, err := g.jsonFields(root.typeOf)
	if err != nil {
		return fmt.Errorf("generate %s: %w", root.name, err)
	}
	fmt.Fprintf(output, "export interface %s {\n", root.name)
	for _, field := range fields {
		typeName, err := g.typeScriptType(field.typeOf)
		if err != nil {
			return fmt.Errorf("generate %s.%s: %w", root.name, field.name, err)
		}
		if override := g.fieldTypes[root.name+"."+field.name]; override != "" {
			typeName = override
		}
		if field.pointer {
			typeName += " | null"
		}
		optional := ""
		if field.optional {
			optional = "?"
			typeName += " | undefined"
		}
		fmt.Fprintf(output, "  readonly %s%s: %s;\n", field.name, optional, typeName)
	}
	output.WriteString("}\n")
	return nil
}

type jsonField struct {
	name     string
	typeOf   reflect.Type
	optional bool
	pointer  bool
}

func (g *generator) jsonFields(typeOf reflect.Type) ([]jsonField, error) {
	var fields []jsonField
	for index := 0; index < typeOf.NumField(); index++ {
		field := typeOf.Field(index)
		if !field.IsExported() {
			continue
		}
		tag := field.Tag.Get("json")
		parts := strings.Split(tag, ",")
		if parts[0] == "-" {
			continue
		}
		if field.Anonymous && parts[0] == "" {
			embedded := field.Type
			if embedded.Kind() == reflect.Pointer {
				embedded = embedded.Elem()
			}
			if embedded.Kind() != reflect.Struct {
				return nil, fmt.Errorf("embedded field %s is not a struct", field.Name)
			}
			nested, err := g.jsonFields(embedded)
			if err != nil {
				return nil, err
			}
			fields = append(fields, nested...)
			continue
		}
		name := parts[0]
		if name == "" {
			name = field.Name
		}
		optional := false
		for _, option := range parts[1:] {
			optional = optional || option == "omitempty"
		}
		fieldType := field.Type
		pointer := fieldType.Kind() == reflect.Pointer
		if pointer {
			fieldType = fieldType.Elem()
		}
		fields = append(fields, jsonField{name: name, typeOf: fieldType, optional: optional, pointer: pointer})
	}
	sort.Slice(fields, func(left, right int) bool { return fields[left].name < fields[right].name })
	return fields, nil
}

func (g *generator) typeScriptType(typeOf reflect.Type) (string, error) {
	if typeOf == rawMessageType {
		return "JSONObject", nil
	}
	if name := g.names[typeOf]; name != "" {
		return name, nil
	}
	if typeOf.PkgPath() == reflect.TypeFor[projection.Field[string]]().PkgPath() && strings.HasPrefix(typeOf.Name(), "Field[") {
		valueType, ok := typeOf.FieldByName("Value")
		if !ok {
			return "", fmt.Errorf("projection field %s has no Value", typeOf)
		}
		value, err := g.typeScriptType(valueType.Type)
		if err != nil {
			return "", err
		}
		return "TelemetryField<" + value + ">", nil
	}
	if typeOf.PkgPath() == reflect.TypeFor[overlayv2.QValue[string]]().PkgPath() && strings.HasPrefix(typeOf.Name(), "QValue[") {
		valueType, ok := typeOf.FieldByName("V")
		if !ok {
			return "", fmt.Errorf("overlay QValue %s has no V", typeOf)
		}
		value, err := g.typeScriptType(valueType.Type)
		if err != nil {
			return "", err
		}
		return "OverlayQValue<" + value + ">", nil
	}

	switch typeOf.Kind() {
	case reflect.Bool:
		return "boolean", nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
		reflect.Float32, reflect.Float64:
		return "number", nil
	case reflect.String:
		return "string", nil
	case reflect.Slice, reflect.Array:
		element, err := g.typeScriptType(typeOf.Elem())
		if err != nil {
			return "", err
		}
		return "readonly " + element + "[]", nil
	case reflect.Map:
		if typeOf.Key().Kind() != reflect.String {
			return "", fmt.Errorf("map key %s is not a string", typeOf.Key())
		}
		value, err := g.typeScriptType(typeOf.Elem())
		if err != nil {
			return "", err
		}
		return "{ readonly [key: string]: " + value + " }", nil
	case reflect.Interface:
		return "unknown", nil
	case reflect.Struct:
		name := g.reachableName(typeOf)
		g.addStruct(typeOf, name)
		return name, nil
	default:
		return "", fmt.Errorf("unsupported Go type %s", typeOf)
	}
}

func (g *generator) reachableName(typeOf reflect.Type) string {
	packageName := filepath.Base(typeOf.PkgPath())
	return exportedIdentifier(packageName) + exportedIdentifier(typeOf.Name())
}

func exportedIdentifier(value string) string {
	words := strings.FieldsFunc(value, func(char rune) bool {
		return char == '-' || char == '_' || char == '.' || char == '/'
	})
	for index, word := range words {
		if word == "" {
			continue
		}
		words[index] = strings.ToUpper(word[:1]) + word[1:]
	}
	return strings.Join(words, "")
}

func (g *generator) sortedEnums() []enumRoot {
	result := make([]enumRoot, 0, len(g.enums))
	for _, root := range g.enums {
		result = append(result, root)
	}
	sort.Slice(result, func(left, right int) bool { return result[left].name < result[right].name })
	return result
}

func (g *generator) sortedStructs() []structRoot {
	result := make([]structRoot, 0, len(g.structs))
	for _, root := range g.structs {
		result = append(result, root)
	}
	sort.Slice(result, func(left, right int) bool { return result[left].name < result[right].name })
	return result
}

func quotedUnion(values []string) string {
	quoted := make([]string, len(values))
	for index, value := range values {
		quoted[index] = fmt.Sprintf("%q", value)
	}
	return strings.Join(quoted, " | ")
}
