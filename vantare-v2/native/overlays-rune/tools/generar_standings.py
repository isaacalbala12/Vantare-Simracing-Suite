"""Compile the existing GPUI Standings tokens; no new source of style values."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT.parent / "ui/styles/standings.json"
TARGET = ROOT / "src/standings/tokens.rs"


def render():
    raw = SOURCE.read_bytes()
    data = json.loads(raw)
    lines = ["// @generated by scripts/generar_standings.py from native/ui/styles/standings.json.",
             "// SHA256: " + hashlib.sha256(raw).hexdigest()]
    for group, fields in data.items():
        for key, value in fields.items():
            name = (group + "_" + key).upper()
            if isinstance(value, (float, int)):
                lines.append(f"pub const {name}: f32 = {float(value)!r};")
            elif isinstance(value, str) and value.startswith("#"):
                lines.append(f"pub const {name}: u32 = 0x{value[1:]};")
            elif value is not None:
                raise ValueError(f"Unsupported canonical token: {group}.{key}")
    return ("\n".join(lines) + "\n").encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if TARGET.read_bytes().replace(b"\r\n", b"\n") != expected:
            raise SystemExit("Regenerate Standings tokens: python tools/generar_standings.py")
    else:
        TARGET.write_bytes(expected)
    print("PASS: Standings tokens match the canonical style")


if __name__ == "__main__":
    main()
