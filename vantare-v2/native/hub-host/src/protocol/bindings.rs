pub fn typescript() -> String {
    let mut text = String::from("// Generated by native/hub-host with ts-rs. Do not edit.\n");
    macro_rules! declaration {($($kind:ty),+)=>{$(text.push_str("export ");text.push_str(&<$kind>::decl(&ts_rs::Config::default()));text.push('\n');)+};}
    declaration!(
        Palette,
        Scheme,
        InterfaceFont,
        MonoFont,
        AppearanceSettings,
        Density,
        Preferences,
        StartupView,
        SettingsView,
        SettingsPatch,
        ThemeBoot,
        WindowBoot,
        LinkState,
        AccessView,
        CoreStatus,
        Topic,
        Request,
        Reply,
        HostError,
        CloseReason,
        Event,
        HostToUi,
        UiToHost
    );
    writeln!(
        text,
        "export const HOST_PROTOCOL_VERSION = {VERSION} as const;"
    )
    .expect("String write");
    for (name, values) in [("methods", METHODS), ("topics", TOPICS)] {
        writeln!(
            text,
            "export const {name} = {} as const;",
            serde_json::to_string(values).expect("names")
        )
        .expect("String write");
    }
    macro_rules! constants {
        ($name:literal, $values:expr) => {
            text.push_str(concat!("export const ", $name, " = "));
            text.push_str(&serde_json::to_string(&$values).expect("serializable constants"));
            text.push_str(" as const;\n");
        };
    }
    constants!("palettes", Palette::ALL);
    constants!("schemes", [Scheme::System, Scheme::Light, Scheme::Dark]);
    constants!(
        "interfaceFonts",
        [
            InterfaceFont::Inter,
            InterfaceFont::Segoe,
            InterfaceFont::Arial
        ]
    );
    constants!(
        "monoFonts",
        [MonoFont::Cascadia, MonoFont::Consolas, MonoFont::Courier]
    );
    constants!(
        "densities",
        [Density::Compact, Density::Balanced, Density::Comfortable]
    );
    constants!("zoomLevels", ZOOM_LEVELS);
    constants!("defaultZoom", DEFAULT_ZOOM);
    constants!("contrastRange", [CONTRAST_MIN, CONTRAST_MAX]);
    constants!("glassOpacityRange", [GLASS_OPACITY_MIN, GLASS_OPACITY_MAX]);
    let fields: Vec<_> = patch_samples()
        .into_iter()
        .map(|patch| {
            serde_json::to_value(patch).expect("patch")["field"]
                .as_str()
                .expect("field")
                .to_owned()
        })
        .collect();
    constants!("settingsFields", fields);
    text.push_str("export const methodsCoverContract: Exclude<Request['method'], typeof methods[number]> extends never ? true : never = true;\nexport const fieldsCoverContract: Exclude<SettingsPatch['field'], typeof settingsFields[number]> extends never ? true : never = true;\n");
    text
}
