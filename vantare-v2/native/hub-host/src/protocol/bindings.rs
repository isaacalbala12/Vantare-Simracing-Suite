pub fn corpus() -> serde_json::Value {
    let mut host = Vec::new();
    let mut ui = Vec::new();
    for (_, _, sample) in module_outputs() {
        host.extend(sample["host"].as_array().expect("host").iter().cloned());
        ui.extend(sample["ui"].as_array().expect("ui").iter().cloned());
    }
    serde_json::json!({"host":host,"ui":ui})
}
pub fn corpus_json() -> String {
    serde_json::to_string_pretty(&canonical(corpus())).expect("corpus") + "\n"
}
#[cfg(test)]
mod tests {
    use super::*;
    use crate::protocol::{
        CloseReason, Event, HostError, LinkState, METHODS, Request, TOPICS, Topic, UiToHost,
    };
    use std::collections::BTreeSet;
    fn names<T: TS>(tag: &str) -> BTreeSet<String> {
        let declaration = T::decl(&ts_rs::Config::default());
        let marker = format!("\"{tag}\": \"");
        declaration
            .split(&marker)
            .skip(1)
            .map(|rest| rest.split('"').next().expect("literal").into())
            .collect()
    }
    fn string_union<T: TS>() -> BTreeSet<String> {
        T::decl(&ts_rs::Config::default())
            .split('"')
            .skip(1)
            .step_by(2)
            .map(str::to_owned)
            .collect()
    }
    fn values<'a>(items: impl Iterator<Item = &'a serde_json::Value>) -> BTreeSet<String> {
        items
            .filter_map(serde_json::Value::as_str)
            .map(str::to_owned)
            .collect()
    }
    #[test]
    fn corpus_covers_every_serde_wire_variant_and_generated_name() {
        let data = corpus();
        let host = data["host"].as_array().expect("host");
        let ui = data["ui"].as_array().expect("ui");
        assert_eq!(
            values(host.iter().map(|item| &item["kind"])),
            names::<HostToUi>("kind")
        );
        assert_eq!(
            values(ui.iter().map(|item| &item["kind"])),
            names::<UiToHost>("kind")
        );
        assert_eq!(
            values(
                ui.iter()
                    .filter(|item| item["request"]["method"] == "privacy.update")
                    .map(|item| &item["request"]["patch"]["field"])
            ),
            names::<crate::privacy::PrivacyPatch>("field")
        );
        let methods = values(ui.iter().map(|item| &item["request"]["method"]));
        assert_eq!(methods, names::<Request>("method"));
        assert_eq!(
            values(
                ui.iter()
                    .filter(|item| item["request"]["method"] == "settings.update")
                    .map(|item| &item["request"]["patch"]["field"])
            ),
            names::<crate::settings::SettingsPatch>("field")
        );
        assert_eq!(
            methods,
            METHODS.iter().map(|value| (*value).into()).collect()
        );
        assert_eq!(
            values(host.iter().map(|item| &item["result"]["method"])),
            names::<Reply>("method")
        );
        assert_eq!(
            values(host.iter().map(|item| &item["error"]["kind"])),
            names::<HostError>("kind")
        );
        assert_eq!(
            values(host.iter().map(|item| &item["event"]["topic"])),
            names::<Event>("topic")
        );
        let topics = values(ui.iter().map(|item| &item["topic"]));
        assert_eq!(topics, string_union::<Topic>());
        assert_eq!(topics, TOPICS.iter().map(|value| (*value).into()).collect());
        assert_eq!(
            values(host.iter().map(|item| &item["reason"])),
            string_union::<CloseReason>()
        );
        assert_eq!(
            values(host.iter().map(|item| &item["event"]["value"]["photos"])),
            string_union::<LinkState>()
        );
    }
    #[test]
    fn corpus_sorting_is_recursive_and_preserves_array_order() {
        let value =
            serde_json::from_str(r#"{"z":{"b":1,"a":2},"a":[{"z":1,"a":2},3]}"#).expect("fixture");
        assert_eq!(
            serde_json::to_string(&canonical(value)).expect("canonical"),
            r#"{"a":[{"a":2,"z":1},3],"z":{"a":2,"b":1}}"#
        );
    }
    #[test]
    fn committed_modules_match_rust() {
        let directory = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../hub-web/src/contract/generated");
        let outputs = module_outputs();
        let expected: BTreeSet<_> = outputs.iter().map(|(id, _, _)| (*id).to_owned()).collect();
        for (path, extension) in [(&directory, "ts"), (&directory.join("corpus"), "json")] {
            let actual: BTreeSet<_> = std::fs::read_dir(path)
                .expect("generated modules")
                .map(|entry| entry.expect("module").path())
                .filter(|path| path.extension().is_some_and(|value| value == extension))
                .map(|path| {
                    path.file_stem()
                        .expect("id")
                        .to_str()
                        .expect("UTF-8")
                        .to_owned()
                })
                .filter(|id| !["contract", "validators"].contains(&id.as_str()))
                .collect();
            assert_eq!(
                actual, expected,
                "only registered Rust modules may be committed"
            );
        }
        for (id, typescript, corpus) in outputs {
            assert_eq!(
                std::fs::read_to_string(directory.join(format!("{id}.ts"))).expect("export module"),
                typescript,
                "types: {id}"
            );
            assert_eq!(
                std::fs::read_to_string(directory.join("corpus").join(format!("{id}.json")))
                    .expect("export corpus"),
                serde_json::to_string_pretty(&canonical(corpus)).expect("corpus") + "\n",
                "corpus: {id}"
            );
        }
    }
}
