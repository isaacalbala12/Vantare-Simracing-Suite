#!/usr/bin/env python3
"""Fail when a Rust `include_*!` reads a path outside its package and the declared inputs.

The slot target is shared between checkouts with the same package names. Cargo
treats those packages as the same unit, so `slot-workspace.ps1` hashes every
workspace package and a declared list of external inputs. If an include reads a
file outside its own package and outside that list, a stale artifact could
survive a checkout switch. This test closes that gap.

Limits: it scans source text, so an include inside a comment fails loudly
(instead of being ignored); it does not follow `#[path]`, `fs::read` or code
generated by a build script that does not contain the literal macro name.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
from pathlib import Path

MACRO = re.compile(r'include(?:_str|_bytes)?!\s*\(')
STRING = re.compile(r'"((?:[^"\\]|\\.)*)"')
ENV = re.compile(r'env!\((?:[^()]|\([^()]*\))*\)')
OUT_DIR = re.compile(r'env!\(\s*"OUT_DIR"\s*\)')
MANIFEST_DIR = re.compile(r'env!\(\s*"CARGO_MANIFEST_DIR"\s*\)')
PACKAGE = re.compile(r'^\s*\[package\]\s*$', re.MULTILINE)


def parse_argument(text: str, start: int) -> str:
    depth = 1
    index = start
    while index < len(text):
        char = text[index]
        if char == '(':
            depth += 1
        elif char == ')':
            depth -= 1
            if depth == 0:
                return text[start:index]
        elif char == '"':
            index += 1
            while index < len(text) and text[index] != '"':
                if text[index] == '\\':
                    index += 1
                index += 1
        index += 1
    raise ValueError('include! sin paréntesis de cierre')


def unquote(value: str) -> str:
    return value.replace('\\\\', '\\').replace('\\"', '"')


def git(*arguments: str, cwd: Path) -> str:
    result = subprocess.run(['git', *arguments], cwd=cwd, capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError(result.stderr.strip() or 'git falló')
    return result.stdout


def package_root(source: Path) -> Path | None:
    current = source.parent
    while current != current.parent:
        manifest = current / 'Cargo.toml'
        if manifest.is_file() and PACKAGE.search(manifest.read_text(encoding='utf-8', errors='replace')):
            return current
        current = current.parent
    return None


def resolve(source: Path, argument: str) -> Path | None:
    if OUT_DIR.search(argument):
        return None
    cleaned = ENV.sub('', argument)
    if 'env!(' in cleaned:
        raise RuntimeError(f'env! desconocido en {source}: {argument.strip()}')
    literals = [unquote(match.group(1)) for match in STRING.finditer(cleaned)]
    if not literals:
        raise RuntimeError(f'sin ruta literal en {source}: {argument.strip()}')
    relative = ''.join(literals)
    if MANIFEST_DIR.search(argument):
        root = package_root(source)
        if root is None:
            raise RuntimeError(f'CARGO_MANIFEST_DIR sin paquete en {source}')
        return (root / relative.lstrip('/')).resolve()
    return (source.parent / relative).resolve()


def inside(path: Path, roots: list[Path]) -> bool:
    return any(path == root or root in path.parents for root in roots)


def main() -> int:
    native = Path(__file__).resolve().parents[1]
    repo = Path(git('rev-parse', '--show-toplevel', cwd=native).strip())
    config = json.loads((native / 'scripts/slot-inputs.json').read_text(encoding='utf-8'))
    external_paths = config.get('external', []) + config.get('rootFiles', [])
    external = [(repo / item).resolve() for item in external_paths]
    missing = [item for item in external if not item.exists()]
    if missing:
        print('Rutas externas declaradas que no existen:', *(str(item.relative_to(repo)) for item in missing), sep='\n  ')
        return 1
    packages: set[Path] = set()
    errors: list[str] = []
    checked = 0
    for source in sorted(native.rglob('*.rs')):
        if '.git' in source.parts or 'target' in source.parts:
            continue
        text = source.read_text(encoding='utf-8', errors='replace')
        for match in MACRO.finditer(text):
            line = text.count('\n', 0, match.start()) + 1
            try:
                target = resolve(source, parse_argument(text, match.end()))
            except (RuntimeError, ValueError) as error:
                errors.append(f'{source.relative_to(repo)}:{line}: {error}')
                continue
            if target is None:
                continue
            checked += 1
            package = package_root(source)
            if package is not None:
                packages.add(package)
                if target == package or package in target.parents:
                    continue
            if inside(target, external):
                continue
            errors.append(f'{source.relative_to(repo)}:{line}: fuera de su paquete y de la lista: {target.relative_to(repo)}')
    print(f'{checked} rutas incluidas comprobadas contra {len(packages)} paquetes y {len(external)} rutas externas')
    if errors:
        print('\n'.join(errors))
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
