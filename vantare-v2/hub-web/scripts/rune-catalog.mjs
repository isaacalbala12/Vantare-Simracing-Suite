// Shared catalog for Rune. No runtime dependency on Node or Electron.

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { sectionIds } from "../src/renderer/app/sections.ts";
import { es, settingsText } from "../src/renderer/i18n/es.ts";
import { roadmap } from "../src/renderer/i18n/roadmap.ts";
import { shellText } from "../src/renderer/i18n/shell.es.ts";

const read = (path) => readFileSync(new URL(path, import.meta.url), "utf8");
const navigation = [
  ...read("../src/renderer/app/navigation.ts").matchAll(
    /\{ id: "([^"]+)", icon: "([^"]+)", label: "([^"]+)" \}/g,
  ),
].map(([, id, icon, key]) => ({
  id,
  icon,
  label:
    id === "studio"
      ? shellText.studioName
      : id === "strategy"
        ? shellText.strategyName
        : id === "engineer"
          ? shellText.engineerName
          : settingsText[key],
}));
if (navigation.length !== 9 || navigation.some((entry) => !entry.label))
  throw new Error("Navigation source changed: update generator");
const strings = {};
for (const [namespace, values] of Object.entries({
  es,
  shell: shellText,
  settings: settingsText,
  roadmap,
})) {
  for (const [key, value] of Object.entries(values))
    if (typeof value === "string") strings[`${namespace}.${key}`] = value;
}
const sentinel = "__VANTARE_NAME__";
const catalog = {
  strings,
  sections: sectionIds,
  navigation,
  launchProfile: shellText.launchProfile(sentinel),
  cases: ["", "Piloto", "áéíóú ñ @ €"].map((input) => ({
    input,
    output: shellText.launchProfile(input),
  })),
};
const iconSource = read("../src/renderer/assets/icons/Icon.tsx");
let icons = "// Generated by hub-web/scripts/rune-catalog.mjs; do not edit.\n";
for (const { icon } of navigation) {
  const svg = iconSource.match(
    new RegExp(`"${icon}": \\((<svg[^\\n]+<\\/svg>)\\)`),
  )?.[1];
  if (!svg) throw new Error(`Missing shared icon ${icon}`);
  const view = svg.match(/viewBox="0 0 (\d+) (\d+)"/);
  if (!view || view[1] !== view[2]) throw new Error("Non square icon");
  const body = svg
    .replace(/^<svg([^>]*)>/, "<g$1>")
    .replace(/<\/svg>$/, "</g>")
    .replace(/strokeWidth/g, "stroke-width")
    .replace(/strokeLinecap/g, "stroke-linecap")
    .replace(/strokeLinejoin/g, "stroke-linejoin")
    .replace(/fillOpacity/g, "fill-opacity");
  icons += `pub static ${icon.replaceAll("-", "_").toUpperCase()}: rune::Icon = rune::Icon { name: ${JSON.stringify(icon)}, view: ${view[1]}.0, body: r##"${body}"## };\n`;
}
icons +=
  "pub fn shared_icon(name: &str) -> &'static rune::Icon { match name {\n";
for (const { icon } of navigation)
  icons += `${JSON.stringify(icon)} => &${icon.replaceAll("-", "_").toUpperCase()},\n`;
icons += '_ => unreachable!("generated navigation icon"),\n} }\n';
icons = execFileSync(
  "rustup",
  ["run", "1.99.1", "rustfmt", "--emit", "stdout", "--edition", "2024"],
  { input: icons, encoding: "utf8" },
).replaceAll("\r\n", "\n");
for (const [path, content] of [
  ["../../hub-rune/src/catalog.json", `${JSON.stringify(catalog, null, 2)}\n`],
  ["../../hub-rune/src/icons.rs", icons],
]) {
  const target = new URL(path, import.meta.url);
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8").replaceAll("\r\n", "\n") !== content)
      throw new Error(`Stale catalog: ${fileURLToPath(target)}`);
  } else writeFileSync(target, content);
}
