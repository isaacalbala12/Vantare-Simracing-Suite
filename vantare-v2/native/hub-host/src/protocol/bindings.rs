macro_rules! constants {
    ($text:expr, $name:literal, $values:expr) => {{
        $text.push_str(concat!("export const ", $name, " = "));
        $text.push_str(
            &serde_json::to_string(&$crate::protocol::bindings::canonical(
                serde_json::to_value(&$values).expect("serializable constants"),
            ))
            .expect("constants JSON"),
        );
        $text.push_str(" as const;\n");
    }};
}
pub(crate) use constants;
pub(crate) fn declare<T: TS>(text: &mut String) {
    writeln!(text, "export {}", T::decl(&ts_rs::Config::default())).expect("String write");
}
pub(crate) fn declare_named<T: TS>(text: &mut String, name: &str) {
    let declaration = T::decl(&ts_rs::Config::default());
    let original = T::ident(&ts_rs::Config::default());
    writeln!(
        text,
        "export {}",
        declaration.replacen(&format!("type {original} ="), &format!("type {name} ="), 1)
    )
    .expect("String write");
}
pub(crate) fn sample_response(result: Reply) -> HostToUi {
    HostToUi::Response { id: 1, result }
}
fn append_names<T: TS>(text: &mut String, id: &str, suffix: &str, tag: &str) {
    let declaration = T::decl(&ts_rs::Config::default());
    let names: std::collections::BTreeSet<_> = if tag.is_empty() {
        declaration
            .split('"')
            .skip(1)
            .step_by(2)
            .map(str::to_owned)
            .collect()
    } else {
        declaration
            .split(&format!("\"{tag}\": \""))
            .skip(1)
            .map(|tail| tail.split('"').next().expect("tag").to_owned())
            .collect()
    };
    writeln!(
        text,
        "export const {id}{suffix} = {} as const;",
        serde_json::to_string(&names).expect("names")
    )
    .expect("String write");
}
fn exported_types(text: &str) -> std::collections::BTreeSet<&str> {
    text.lines()
        .filter_map(|line| line.strip_prefix("export type "))
        .filter_map(|line| line.split_whitespace().next())
        .collect()
}
fn add_type_imports(modules: &mut [(&str, String, serde_json::Value)]) {
    let names: std::collections::BTreeSet<String> = modules
        .iter()
        .flat_map(|(_, text, _)| exported_types(text).into_iter().map(str::to_owned))
        .chain(["Request", "Reply", "HostError", "Topic", "Event"].map(str::to_owned))
        .collect();
    for (_, text, _) in modules {
        let own = exported_types(text);
        let words: std::collections::BTreeSet<_> = text
            .split(|c: char| !c.is_ascii_alphanumeric() && c != '_')
            .collect();
        let used: Vec<_> = names
            .iter()
            .filter(|name| !own.contains(name.as_str()) && words.contains(name.as_str()))
            .map(String::as_str)
            .collect();
        let prefix = if used.is_empty() {
            String::new()
        } else {
            format!(
                "import type {{ {} }} from \"./contract\";\n",
                used.join(", ")
            )
        };
        *text = format!("// Generated by native/hub-host with ts-rs. Do not edit.\n{prefix}{text}");
    }
}
fn module_prefix(id: &str) -> String {
    id.split('_')
        .map(|part| {
            let mut part = part.to_owned();
            part[..1].make_ascii_uppercase();
            part
        })
        .collect()
}
pub fn typescript() -> String {
    let modules = module_outputs();
    let mut text = String::from("// Generated index. Run bun run contract:index.\n");
    for (id, _, _) in &modules {
        writeln!(text, "export * from \"./{id}\";").expect("String write");
    }
    for kind in ["Request", "Reply", "HostError", "Topic", "Event"] {
        let names: Vec<_> = modules
            .iter()
            .flat_map(|(id, source, _)| {
                exported_types(source)
                    .into_iter()
                    .filter(|name| *name == format!("{}{kind}", module_prefix(id)))
                    .map(str::to_owned)
            })
            .collect();
        for (id, source, _) in &modules {
            let owned: Vec<_> = names
                .iter()
                .filter(|name| source.contains(&format!("export type {name} =")))
                .map(String::as_str)
                .collect();
            if !owned.is_empty() {
                writeln!(
                    text,
                    "import type {{ {} }} from \"./{id}\";",
                    owned.join(", ")
                )
                .expect("String write");
            }
        }
        writeln!(text, "export type {kind} = {};", names.join(" | ")).expect("String write");
    }
    for (kind, suffix) in [("methods", "Methods"), ("topics", "Topics")] {
        let names: Vec<_> = modules
            .iter()
            .filter(|(_, source, _)| source.contains(&format!("{suffix} =")))
            .map(|(id, _, _)| format!("{id}{suffix}"))
            .collect();
        for (id, source, _) in &modules {
            if source.contains(&format!("{suffix} =")) {
                writeln!(text, "import {{ {id}{suffix} }} from \"./{id}\";").expect("String write");
            }
        }
        writeln!(
            text,
            "export const {kind} = [{}] as const;",
            names
                .iter()
                .map(|name| format!("...{name}"))
                .collect::<Vec<_>>()
                .join(", ")
        )
        .expect("String write");
    }
    text
}
pub(crate) fn canonical(value: serde_json::Value) -> serde_json::Value {
    match value {
        serde_json::Value::Object(object) => {
            let ordered: std::collections::BTreeMap<_, _> = object
                .into_iter()
                .map(|(key, value)| (key, canonical(value)))
                .collect();
            serde_json::Value::Object(ordered.into_iter().collect())
        }
        serde_json::Value::Array(values) => {
            serde_json::Value::Array(values.into_iter().map(canonical).collect())
        }
        value => value,
    }
}
