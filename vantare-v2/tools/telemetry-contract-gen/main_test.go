type tsField struct {
	typeName string
	optional bool
}

func TestGeneratedContractMatchesHandwritten(t *testing.T) {
	t.Parallel()

	generatedBytes, err := generate()
	if err != nil {
		t.Fatalf("generate contract: %v", err)
	}
	generated := string(generatedBytes)
	transport := handwrittenTransportContract
	overlayMirror := readRepositoryFile(t, "frontend", "src", "overlay", "projection", "overlay-projection-v1.ts")

	compareFields(t, "ProjectionEnvelope",
		interfaceFields(t, generated, "ProjectionEnvelope"),
		typeLiteralFields(t, transport, "ProjectionEnvelope"), nil)
	compareFields(t, "StatusEnvelope",
		withoutField(interfaceFields(t, generated, "StatusEnvelope"), "payload"),
		withoutField(typeLiteralFields(t, transport, "StatusEnvelope"), "payload"), nil)
	compareFields(t, "StatusPayload",
		interfaceFields(t, generated, "StatusPayload"),
		nestedTypeLiteralFields(t, transport, "StatusEnvelope", "payload"), nil)
	compareFields(t, "FactEnvelope",
		interfaceFields(t, generated, "FactEnvelope"),
		typeLiteralFields(t, transport, "FactEnvelope"), nil)

	fieldAliases := map[string]string{
		"TelemetryField": "OverlayProjectionField",
	}
	vehicle := interfaceFields(t, generated, "OverlayVehicleV1")
	compareFields(t, "OverlayVehicleV1", vehicle,
		typeLiteralFields(t, overlayMirror, "OverlayVehicleV1"), fieldAliases)
	if got := len(vehicle); got != 30 {
		t.Fatalf("OverlayVehicleV1 generated %d fields; Go wire currently has 30", got)
	}
	compareFields(t, "OverlayGroundPositionV1",
		interfaceFields(t, generated, "OverlayGroundPositionV1"),
		typeLiteralFields(t, overlayMirror, "OverlayGroundPositionV1"), nil)

	compareValues(t, "ProductID", enumValues(t, generated, "ProductID"),
		constArrayValues(t, transport, "TELEMETRY_PRODUCTS"))
	compareValues(t, "StatusState", enumValues(t, generated, "StatusState"),
		constArrayValues(t, transport, "TELEMETRY_STATUS_STATES"))
	compareValues(t, "SnapshotKind", enumValues(t, generated, "SnapshotKind"), []string{"full"})
	compareValues(t, "EventKind", enumValues(t, generated, "EventKind"), []string{"projection", "status", "fact"})
}

func TestGeneratedOverlayV2ContractUsesCompactGenericQuality(t *testing.T) {
	t.Parallel()

	generatedBytes, err := generate()
	if err != nil {
		t.Fatalf("generate contract: %v", err)
	}
	generated := string(generatedBytes)
	compareFields(t, "OverlayUpdateV2", interfaceFields(t, generated, "OverlayUpdateV2"), map[string]tsField{
		"revision": {typeName: "number"},
		"source":   {typeName: "OverlaySourceStatusV2"},
		"frame":    {typeName: "OverlayFrameV2 | null"},
	}, nil)
	compareFields(t, "OverlayQValue", interfaceFields(t, generated, "OverlayQValue<T>"), map[string]tsField{
		"q": {typeName: "OverlayQualityV2"},
		"v": {typeName: "T | undefined", optional: true},
	}, nil)
	compareValues(t, "OverlayQualityV2", enumValues(t, generated, "OverlayQualityV2"),
		[]string{"fresh", "invalid", "missing", "stale"})
	if strings.Contains(generated, "interface Overlayv2QValue") {
		t.Fatal("generic QValue was emitted as a duplicated concrete interface")
	}
}

