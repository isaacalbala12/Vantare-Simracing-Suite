"""Generate typed Rune tokens from the single canonical Vantare JSON style."""
from __future__ import annotations
import argparse
import hashlib
import json
import math
import re
import subprocess
from pathlib import Path


def render(source: Path) -> dict[str, bytes]:
    raw = source.read_bytes()
    value = json.loads(raw)
    shapes: dict[tuple, str] = {}
    definitions: list[str] = []

    def signature(item):
        if isinstance(item, dict):
            return ("object", tuple(sorted((key, signature(child)) for key, child in item.items())))
        if isinstance(item, list):
            if not item or any(signature(child) != signature(item[0]) for child in item):
                raise ValueError("style arrays must contain one known shape")
            return ("array", signature(item[0]))
        if isinstance(item, bool):
            return ("bool",)
        if isinstance(item, (int, float)) and math.isfinite(item):
            return ("number",)
        if isinstance(item, str):
            return ("color" if re.fullmatch(r"#[0-9a-fA-F]{6}(?:[0-9a-fA-F]{2})?", item) else "string",)
        raise ValueError("unsupported canonical token")

    def field(key: str) -> str:
        return "matches" if key == "match" else key

    def named(path: str) -> str:
        return "".join(word.title() for word in re.split(r"[._]", path)) or "Style"

    def rust_type(item, path: str) -> str:
        sig = signature(item)
        if sig[0] == "object":
            if sig in shapes:
                return shapes[sig]
            name = named(path)
            shapes[sig] = name
            members = [f"    pub {field(key)}: {rust_type(child, path + '.' + key if path else key)}," for key, child in item.items()]
            definitions.append("#[derive(Clone, Debug, PartialEq)]\npub struct " + name + " {\n" + "\n".join(members) + "\n}\n")
            return name
        if sig[0] == "array":
            return "Vec<" + rust_type(item[0], path + "_item") + ">"
        return {"bool":"bool", "number":"f32", "color":"rune::Color", "string":"&'static str"}[sig[0]]

    def literal(item, path: str) -> str:
        sig = signature(item)
        if sig[0] == "object":
            fields = [field(key) + ": " + literal(child, path + '.' + key if path else key) for key, child in item.items()]
            return shapes[sig] + " { " + ", ".join(fields) + " }"
        if sig[0] == "array":
            return "vec![" + ", ".join(literal(child, path + "_item") for child in item) + "]"
        if sig[0] == "color":
            return "rune::color::hex(" + json.dumps(item) + ').expect("canonical Vantare color")'
        if sig[0] == "number":
            return repr(float(item))
        if sig[0] == "bool":
            return str(item).lower()
        if any(ord(ch) < 32 for ch in item):
            raise ValueError("control character in canonical style string")
        return json.dumps(item, ensure_ascii=False)

    rust_type(value, "")
    header = "// @generated by tools/generar_vantare.py; edit native/ui/styles/vantare.json.\n"
    header += "// Canonical source SHA256: " + hashlib.sha256(raw).hexdigest() + "\n"
    code = header + "\n".join(definitions) + "\npub fn compiled() -> Style { " + literal(value, "") + " }\n"
    formatted = subprocess.run(["rustfmt", "+1.99.1", "--edition", "2024", "--emit", "stdout"], input=code.encode(), stdout=subprocess.PIPE, check=True).stdout
    return {"src/vantare/generated.rs": formatted.replace(b"\r\n", b"\n")}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    workspace = Path(__file__).resolve().parents[1]
    outputs = render(workspace.parent / "ui/styles/vantare.json")
    stale = []
    for relative, expected in outputs.items():
        target = workspace / relative
        if args.check:
            if not target.is_file() or target.read_bytes() != expected:
                stale.append(relative)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(expected)
    if stale:
        raise SystemExit("Regenerate Rune Vantare tokens: " + ", ".join(stale))
    print("PASS: Rune Vantare tokens match the canonical product style")


if __name__ == "__main__":
    main()
