pub fn corpus() -> serde_json::Value {
    let settings = settings_sample();
    let mut host = vec![hello(&settings).expect("boot view")];
    for state in [
        LinkState::Connected,
        LinkState::Incompatible,
        LinkState::Unavailable,
    ] {
        let value = CoreStatus {
            photos: state,
            rights: state,
            services: state,
            ..Default::default()
        };
        host.push(HostToUi::Response {
            id: 1,
            result: Reply::Core {
                value: value.clone(),
            },
        });
        host.push(HostToUi::Event {
            event: Event::Core { value },
        });
    }
    for result in [
        Reply::SettingsGet {
            value: settings.clone(),
        },
        Reply::SettingsUpdate {
            value: settings.clone(),
        },
        Reply::SettingsRetry {
            value: settings.clone(),
        },
        Reply::SettingsDiscard {
            value: settings.clone(),
        },
        Reply::NotificationTest { accepted: true },
        Reply::LauncherFavorite { accepted: false },
    ] {
        host.push(HostToUi::Response { id: 1, result });
    }
    host.push(HostToUi::Event {
        event: Event::SimStatus { live: true },
    });
    let mut current = settings.clone();
    current.can_retry = true;
    for error in [
        HostError::Busy,
        HostError::CoreUnavailable,
        HostError::Unsupported,
        HostError::Incompatible {
            expected: VERSION,
            found: VERSION + 1,
        },
        HostError::Denied,
        HostError::Protected,
        HostError::Io,
        HostError::Conflict { current },
    ] {
        host.push(HostToUi::Failure { id: 1, error });
    }
    for reason in [
        CloseReason::Window,
        CloseReason::Live,
        CloseReason::ControlEof,
    ] {
        host.push(HostToUi::CloseRequested { reason });
    }
    serde_json::json!({"host":host,"ui":ui_samples()})
}

fn ui_samples() -> Vec<UiToHost> {
    let mut ui = vec![
        UiToHost::Hello { version: VERSION },
        UiToHost::Subscribe { topic: Topic::Core },
        UiToHost::Subscribe {
            topic: Topic::SimStatus,
        },
        UiToHost::Unsubscribe { topic: Topic::Core },
        UiToHost::Unsubscribe {
            topic: Topic::SimStatus,
        },
        UiToHost::Ready {},
        UiToHost::CloseAnswer { allow: true },
        UiToHost::CloseAnswer { allow: false },
    ];
    for request in [
        Request::CoreGet {},
        Request::WindowClose {},
        Request::SettingsGet {},
        Request::SettingsRetry {},
        Request::SettingsDiscard {},
        Request::LauncherFavorite {},
        Request::NotificationTest {},
    ] {
        ui.push(UiToHost::Request { id: 1, request });
    }
    for patch in patch_samples() {
        ui.push(UiToHost::Request {
            id: 1,
            request: Request::SettingsUpdate {
                patch,
                base_revision: "0".repeat(64),
            },
        });
    }
    ui
}

pub fn corpus_json() -> String {
    serde_json::to_string_pretty(&corpus()).expect("wire corpus") + "\n"
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;
    fn names<T: TS>(tag: &str) -> BTreeSet<String> {
        let declaration = T::decl(&ts_rs::Config::default());
        let marker = format!("\"{tag}\": \"");
        declaration
            .split(&marker)
            .skip(1)
            .map(|rest| rest.split('"').next().expect("literal").into())
            .collect()
    }
    fn string_union<T: TS>() -> BTreeSet<String> {
        T::decl(&ts_rs::Config::default())
            .split('"')
            .skip(1)
            .step_by(2)
            .map(str::to_owned)
            .collect()
    }
    fn values<'a>(items: impl Iterator<Item = &'a serde_json::Value>) -> BTreeSet<String> {
        items
            .filter_map(serde_json::Value::as_str)
            .map(str::to_owned)
            .collect()
    }
    #[test]
    fn corpus_covers_every_serde_wire_variant_and_generated_name() {
        let data = corpus();
        let host = data["host"].as_array().expect("host");
        let ui = data["ui"].as_array().expect("ui");
        assert_eq!(
            values(host.iter().map(|item| &item["kind"])),
            names::<HostToUi>("kind")
        );
        assert_eq!(
            values(ui.iter().map(|item| &item["kind"])),
            names::<UiToHost>("kind")
        );
        let methods = values(ui.iter().map(|item| &item["request"]["method"]));
        assert_eq!(methods, names::<Request>("method"));
        assert_eq!(
            values(ui.iter().map(|item| &item["request"]["patch"]["field"])),
            names::<SettingsPatch>("field")
        );
        assert_eq!(
            methods,
            METHODS.iter().map(|value| (*value).into()).collect()
        );
        assert_eq!(
            values(host.iter().map(|item| &item["result"]["method"])),
            names::<Reply>("method")
        );
        assert_eq!(
            values(host.iter().map(|item| &item["error"]["kind"])),
            names::<HostError>("kind")
        );
        assert_eq!(
            values(host.iter().map(|item| &item["event"]["topic"])),
            names::<Event>("topic")
        );
        let topics = values(ui.iter().map(|item| &item["topic"]));
        assert_eq!(topics, string_union::<Topic>());
        assert_eq!(topics, TOPICS.iter().map(|value| (*value).into()).collect());
        assert_eq!(
            values(host.iter().map(|item| &item["reason"])),
            string_union::<CloseReason>()
        );
        assert_eq!(
            values(host.iter().map(|item| &item["event"]["value"]["photos"])),
            string_union::<LinkState>()
        );
    }
    #[test]
    fn committed_corpus_is_exactly_the_rust_serialization() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../hub-web/src/contract/generated/corpus.json");
        assert_eq!(
            std::fs::read_to_string(path).expect("export corpus first"),
            corpus_json()
        );
    }
}
