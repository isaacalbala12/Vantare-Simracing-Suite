const defaultOutput = "frontend/src/generated/telemetry.ts"

var rawMessageType = reflect.TypeFor[json.RawMessage]()

type enumRoot struct {
	typeOf reflect.Type
	name   string
	values []string
}

type structRoot struct {
	typeOf reflect.Type
	name   string
}

type generator struct {
	names      map[reflect.Type]string
	structs    map[reflect.Type]structRoot
	enums      map[reflect.Type]enumRoot
	fieldTypes map[string]string
	reserved   map[string]reflect.Type
}

func main() {
	output := flag.String("out", defaultOutput, "generated TypeScript output path")
	check := flag.Bool("check", false, "compare a temporary generation with the committed output")
	flag.Parse()

	generated, err := generate()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if *check {
		if err := checkGenerated(*output, generated); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		return
	}
	if err := os.MkdirAll(filepath.Dir(*output), 0o755); err != nil {
		fmt.Fprintf(os.Stderr, "create output directory: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*output, generated, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "write generated contract: %v\n", err)
		os.Exit(1)
	}
}

func checkGenerated(output string, generated []byte) error {
	temporary, err := os.CreateTemp("", "vantare-telemetry-contract-*.ts")
	if err != nil {
		return fmt.Errorf("create temporary contract: %w", err)
	}
	temporaryPath := temporary.Name()
	defer os.Remove(temporaryPath)
	if _, err := temporary.Write(generated); err != nil {
		temporary.Close()
		return fmt.Errorf("write temporary contract: %w", err)
	}
	if err := temporary.Close(); err != nil {
		return fmt.Errorf("close temporary contract: %w", err)
	}

	committed, err := os.Open(output)
	if err != nil {
		return fmt.Errorf("open committed contract: %w", err)
	}
	defer committed.Close()
	temporary, err = os.Open(temporaryPath)
	if err != nil {
		return fmt.Errorf("open temporary contract: %w", err)
	}
	defer temporary.Close()
	equal, err := sameBytes(committed, temporary)
	if err != nil {
		return fmt.Errorf("compare generated contract: %w", err)
	}
	if !equal {
		return fmt.Errorf("%s is stale; regenerate with `task telemetry:contract`", output)
	}
	return nil
}

func sameBytes(left, right io.Reader) (bool, error) {
	leftBytes, err := io.ReadAll(left)
	if err != nil {
		return false, err
	}
	rightBytes, err := io.ReadAll(right)
	if err != nil {
		return false, err
	}
	return bytes.Equal(leftBytes, rightBytes), nil
}

func generate() ([]byte, error) {
	g := newGenerator()
	var body bytes.Buffer
	body.WriteString("// DO NOT EDIT — generated by tools/telemetry-contract-gen from internal/telemetry/projection/{overlay,overlayv2,engineer,strategy,analysis}, internal/telemetry/schema/envelope, and internal/app/telemetrytransport; regenerate with `task telemetry:contract`.\n\n")
	body.WriteString("export type JSONValue = null | boolean | number | string | JSONValue[] | { [key: string]: JSONValue };\n")
	body.WriteString("export type JSONObject = { [key: string]: JSONValue };\n\n")

	for _, enum := range g.sortedEnums() {
		fmt.Fprintf(&body, "export type %s = %s;\n", enum.name, quotedUnion(enum.values))
	}
	body.WriteString("\n")
	if err := g.writeTelemetryField(&body); err != nil {
		return nil, err
	}
	body.WriteString("\n")
	if err := g.writeOverlayQValue(&body); err != nil {
		return nil, err
	}
	body.WriteString("\n")

	for len(g.structs) > 0 {
		roots := g.sortedStructs()
		g.structs = make(map[reflect.Type]structRoot)
		for _, root := range roots {
			if err := g.writeInterface(&body, root); err != nil {
				return nil, err
			}
			body.WriteString("\n")
		}
	}

	// EventFact remains a reserved Go wire kind after F4. This compatibility
	// envelope keeps the existing frontend API compiling until F7 owns facts.
	body.WriteString("/** @deprecated Reserved for the F7 Engineer facts port; no live fact transport exists in F5. */\n")
	body.WriteString("export interface FactEnvelope {\n")
	body.WriteString("  readonly capturedAt: string;\n")
	body.WriteString("  readonly epoch: number;\n")
	body.WriteString("  readonly factSequence: number;\n")
	body.WriteString("  readonly payload: JSONObject;\n")
	body.WriteString("  readonly product: ProductID;\n")
	body.WriteString("  readonly projectionVersion: number;\n")
	body.WriteString("  readonly sequence: number;\n")
	body.WriteString("  readonly statusRevision: number;\n")
	body.WriteString("}\n\n")
	body.WriteString("export type TransportEvent =\n")
	body.WriteString("  | { readonly kind: \"projection\"; readonly value: ProjectionEnvelope }\n")
	body.WriteString("  | { readonly kind: \"status\"; readonly value: StatusEnvelope }\n")
	body.WriteString("  | { readonly kind: \"fact\"; readonly value: FactEnvelope };\n")

	return body.Bytes(), nil
}

