import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

// Local tokens derived from the frozen GPUI assistant, including its approved
// dark literals. Other palettes retain the live skin mapping from paint().
const sources = ["view.rs", "art.rs"].map((name) =>
  readFileSync(
    new URL(`../../native/hub/src/shell/onboarding/${name}`, import.meta.url),
    "utf8",
  ),
);
const [view] = sources;
const paint = view.slice(
  view.indexOf("match color {"),
  view.indexOf("/// Tema con"),
);
const skin: Record<string, string> = {
  base: "--bg-base",
  l1: "--surface-1",
  l2: "--surface-2",
  l3: "--surface-3",
  el: "--surface-elevated",
  accent: "--accent",
  text1: "--text-1",
  on_primary: "--text-on-primary",
  text2: "--text-2",
  text3: "--text-3",
  ok: "--ok",
  err: "--err",
};
const hex = (raw: string) => raw.replaceAll("_", "").slice(-6).toLowerCase();
const colors = [
  ...new Set(
    sources.flatMap((source) =>
      [...source.matchAll(/0x([0-9a-fA-F_]+)/g)].map((match) => hex(match[1])),
    ),
  ),
].sort();
const mapped = new Map<string, string>();
for (const match of paint.matchAll(
  /((?:0x[0-9a-f_]+(?:\s*\|\s*)?)+)\s*=>\s*skin\.(\w+)/g,
)) {
  const token = skin[match[2]];
  if (!token) throw new Error(`Unknown GPUI skin field ${match[2]}`);
  for (const color of match[1].matchAll(/0x([0-9a-f_]+)/g))
    mapped.set(hex(color[1]), `var(${token})`);
}
if (mapped.size !== 20 || !paint.includes("mix(skin.accent, skin.l1, 0.15)"))
  throw new Error("GPUI paint mapping changed; review the assistant tokens");
mapped.set("190d0e", "color-mix(in srgb, var(--accent) 15%, var(--surface-1))");
let css = `/* Generated by scripts/onboarding-colors.ts. Frozen GPUI sha256: ${createHash("sha256").update(sources.join("\n")).digest("hex")} */\n.v-onboarding {\n`;
for (const color of colors) css += `  --ob-raw-${color}: #${color};\n`;
for (const color of colors)
  css += `  --ob-c-${color}: ${mapped.get(color) ?? `#${color}`};\n`;
css += '}\n[data-palette="vantare"][data-scheme="dark"] .v-onboarding {\n';
for (const color of mapped.keys()) css += `  --ob-c-${color}: #${color};\n`;
css += "}\n";
// The art panel always takes the dark hero, also in a light Hub.
const tokens = readFileSync(
  new URL("../src/renderer/design/generated/tokens.css", import.meta.url),
  "utf8",
);
let heroes = 0;
for (const match of tokens.matchAll(
  /\[data-palette="([a-z]+)"\]\[data-scheme="dark"\] \{([\s\S]*?)\n\}/g,
)) {
  const gradient = /--grad-hero: ([^;]+);/.exec(match[2])?.[1];
  if (!gradient) throw new Error(`Missing dark hero for ${match[1]}`);
  css += `[data-palette="${match[1]}"] .v-onboarding { --ob-art-gradient: ${gradient}; }\n`;
  heroes++;
}
if (!heroes) throw new Error("Missing native dark hero tokens");
const target = new URL(
  "../src/renderer/design/generated/onboarding.css",
  import.meta.url,
);
mkdirSync(new URL(".", target), { recursive: true });
writeFileSync(target, css);
